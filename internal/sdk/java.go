// javaApiException renders the thrown-on-non-2xx exception, carrying the
// decoded body for inspection.
func javaApiException(pkg string) string {
	return fmt.Sprintf(`package %s;

// Code generated by specter. Edit freely — it is yours now.
public class ApiException extends RuntimeException {
    public final int status;
    public final Object body;

    public ApiException(int status, Object body) {
        super("request failed: " + status);
        this.status = status;
        this.body = body;
    }
}
`, pkg)
}

// javaJsonRuntime renders Json.java: a hand-written, dependency-free JSON
// library. parse(String) yields Map<String,Object>/List<Object>/String/Double/
// Boolean/null; write(Object) serializes those types back to text. The asX and
// mapList helpers back the generated fromJson/toJson.
func javaJsonRuntime(pkg string) string {
	return fmt.Sprintf("package %s;\n\n%s", pkg, javaJsonBody)
}

const javaJsonBody = `import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Function;

// Code generated by specter. Edit freely — it is yours now.

/** A tiny dependency-free JSON runtime: parse text to Object trees and back. */
public final class Json {
    private Json() {}

    // ---- coercion helpers used by generated fromJson/toJson ----
    public static String asString(Object o) { return o == null ? null : o.toString(); }

    public static long asLong(Object o) { return o == null ? 0L : ((Number) o).longValue(); }

    public static double asDouble(Object o) { return o == null ? 0.0 : ((Number) o).doubleValue(); }

    public static boolean asBool(Object o) { return o != null && (Boolean) o; }

    @SuppressWarnings("unchecked")
    public static Map<String, Object> asMap(Object o) { return (Map<String, Object>) o; }

    @SuppressWarnings("unchecked")
    public static List<Object> asList(Object o) { return (List<Object>) o; }

    public static <A, B> List<B> mapList(List<A> in, Function<A, B> f) {
        List<B> out = new ArrayList<>();
        if (in != null) {
            for (A x : in) out.add(f.apply(x));
        }
        return out;
    }

    // ---- parser (recursive descent) ----
    public static Object parse(String s) {
        Parser p = new Parser(s);
        p.ws();
        Object v = p.value();
        p.ws();
        if (!p.end()) throw p.err("trailing data");
        return v;
    }

    private static final class Parser {
        final String s;
        int pos;

        Parser(String s) { this.s = s; }

        boolean end() { return pos >= s.length(); }

        char peek() { return s.charAt(pos); }

        char next() {
            if (end()) throw err("unexpected end of input");
            return s.charAt(pos++);
        }

        void ws() {
            while (!end()) {
                char c = peek();
                if (c == ' ' || c == '\t' || c == '\n' || c == '\r') pos++;
                else break;
            }
        }

        Object value() {
            if (end()) throw err("unexpected end of input");
            char c = peek();
            switch (c) {
                case '{': return object();
                case '[': return array();
                case '"': return string();
                case 't':
                case 'f': return bool();
                case 'n': return nul();
                default: return number();
            }
        }

        Map<String, Object> object() {
            expect('{');
            ws();
            Map<String, Object> m = new LinkedHashMap<>();
            if (peek() == '}') { pos++; return m; }
            while (true) {
                ws();
                String k = string();
                ws();
                expect(':');
                ws();
                m.put(k, value());
                ws();
                char c = next();
                if (c == '}') return m;
                if (c != ',') throw err("expected ',' or '}'");
            }
        }

        List<Object> array() {
            expect('[');
            ws();
            List<Object> a = new ArrayList<>();
            if (peek() == ']') { pos++; return a; }
            while (true) {
                ws();
                a.add(value());
                ws();
                char c = next();
                if (c == ']') return a;
                if (c != ',') throw err("expected ',' or ']'");
            }
        }

        String string() {
            expect('"');
            StringBuilder sb = new StringBuilder();
            while (true) {
                char c = next();
                if (c == '"') return sb.toString();
                if (c == '\\') {
                    char e = next();
                    switch (e) {
                        case '"': sb.append('"'); break;
                        case '\\': sb.append('\\'); break;
                        case '/': sb.append('/'); break;
                        case 'b': sb.append('\b'); break;
                        case 'f': sb.append('\f'); break;
                        case 'n': sb.append('\n'); break;
                        case 'r': sb.append('\r'); break;
                        case 't': sb.append('\t'); break;
                        case 'u':
                            String hex = s.substring(pos, pos + 4);
                            pos += 4;
                            sb.append((char) Integer.parseInt(hex, 16));
                            break;
                        default: throw err("invalid escape '\\" + e + "'");
                    }
                } else {
                    sb.append(c);
                }
            }
        }

        Object number() {
            int start = pos;
            while (!end()) {
                char c = peek();
                if ((c >= '0' && c <= '9') || c == '-' || c == '+' || c == '.' || c == 'e' || c == 'E') pos++;
                else break;
            }
            String num = s.substring(start, pos);
            if (num.isEmpty()) throw err("invalid number");
            return Double.parseDouble(num);
        }

        Boolean bool() {
            if (s.startsWith("true", pos)) { pos += 4; return Boolean.TRUE; }
            if (s.startsWith("false", pos)) { pos += 5; return Boolean.FALSE; }
            throw err("invalid literal");
        }

        Object nul() {
            if (s.startsWith("null", pos)) { pos += 4; return null; }
            throw err("invalid literal");
        }

        void expect(char c) {
            if (next() != c) throw err("expected '" + c + "'");
        }

        IllegalArgumentException err(String m) {
            return new IllegalArgumentException("json: " + m + " at position " + pos);
        }
    }

    // ---- serializer ----
    public static String write(Object o) {
        StringBuilder sb = new StringBuilder();
        writeValue(sb, o);
        return sb.toString();
    }

    private static void writeValue(StringBuilder sb, Object o) {
        if (o == null) { sb.append("null"); return; }
        if (o instanceof String str) { writeString(sb, str); return; }
        if (o instanceof Boolean b) { sb.append(b.booleanValue()); return; }
        if (o instanceof Double d) { sb.append(fmtNum(d)); return; }
        if (o instanceof Float f) { sb.append(fmtNum(f.doubleValue())); return; }
        if (o instanceof Number n) { sb.append(n.toString()); return; }
        if (o instanceof Map<?, ?> m) { writeObject(sb, m); return; }
        if (o instanceof List<?> l) { writeArray(sb, l); return; }
        writeString(sb, o.toString());
    }

    private static String fmtNum(double d) {
        if (d == Math.rint(d) && !Double.isInfinite(d)) return Long.toString((long) d);
        return Double.toString(d);
    }

    private static void writeObject(StringBuilder sb, Map<?, ?> m) {
        sb.append('{');
        boolean first = true;
        for (Map.Entry<?, ?> e : m.entrySet()) {
            if (!first) sb.append(',');
            first = false;
            writeString(sb, String.valueOf(e.getKey()));
            sb.append(':');
            writeValue(sb, e.getValue());
        }
        sb.append('}');
    }

    private static void writeArray(StringBuilder sb, List<?> l) {
        sb.append('[');
        boolean first = true;
        for (Object x : l) {
            if (!first) sb.append(',');
            first = false;
            writeValue(sb, x);
        }
        sb.append(']');
    }

    private static void writeString(StringBuilder sb, String s) {
        sb.append('"');
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"': sb.append("\\\""); break;
                case '\\': sb.append("\\\\"); break;
                case '\n': sb.append("\\n"); break;
                case '\r': sb.append("\\r"); break;
                case '\t': sb.append("\\t"); break;
                case '\b': sb.append("\\b"); break;
                case '\f': sb.append("\\f"); break;
                default:
                    if (c < 0x20) sb.append(String.format("\\u%04x", (int) c));
                    else sb.append(c);
            }
        }
        sb.append('"');
    }
}
`

// generateJava renders a dependency-free Java 17 client. Java's standard
// library has no typed JSON binding, so this emits its own tiny JSON runtime
// (Json.java): a recursive-descent parser producing Map/List/Double/Boolean/
// String/null trees, and a serializer back to text. Every model is a record
// with fromJson/toJson that map wire keys to camelCase components, and the
// Client funnels each operation through java.net.http.HttpClient.
//
// javac requires each public top-level type in its own correctly named file,
// so the output is several File entries: Json.java, ApiException.java,
// Client.java, and one <Type>.java per struct schema. They share a package
// (opts.Package, or "apiclient") and compile together as one unit.
func generateJava(doc *core.Document, opts Options) ([]File, error) {
	pkg := opts.Package
	if pkg == "" {
		pkg = "apiclient"
	}

	var files []File
	files = append(files, File{Name: "Json.java", Data: []byte(javaJsonRuntime(pkg))})
	files = append(files, File{Name: "ApiException.java", Data: []byte(javaApiException(pkg))})

	// One record file per struct schema.
	for _, name := range sortedSchemaNames(doc) {
		s := doc.Components.Schemas[name]
		if s == nil || !isStruct(s) || aliasTarget(s) != nil {
			// Aliases and non-object schemas need no class: their referents
			// resolve straight to a Java type at every use site.
			continue
		}
		typeName := pascalCase(name)
		files = append(files, File{
			Name: typeName + ".java",
			Data: []byte(javaModel(doc, pkg, typeName, s)),
		})
	}

	files = append(files, File{Name: "Client.java", Data: []byte(javaClient(doc, pkg, opts))})
	return files, nil
}

// javaModel renders one record: typed components, a static fromJson factory
// that decodes a wire Map, and a toJson that rebuilds the wire Map with the
// original key names.
func javaModel(doc *core.Document, pkg, typeName string, s *core.Schema) string {
	var b strings.Builder
	fmt.Fprintf(&b, "package %s;\n\n", pkg)
	b.WriteString("import java.util.*;\n\n")
	b.WriteString("// Code generated by specter. Edit freely — it is yours now.\n")

	fields := resolvedFields(doc, s)

	// Record header: component list.
	var comps []string
	for _, f := range fields {
		comps = append(comps, fmt.Sprintf("%s %s", javaType(doc, f.Schema), javaFieldName(f.Name)))
	}
	fmt.Fprintf(&b, "public record %s(%s) {\n", typeName, strings.Join(comps, ", "))

	// fromJson: null-safe cast of the payload, then component-by-component decode
	// keyed by the original wire names.
	fmt.Fprintf(&b, "    public static %s fromJson(Object o) {\n", typeName)
	b.WriteString("        if (o == null) return null;\n")
	if len(fields) == 0 {
		fmt.Fprintf(&b, "        return new %s();\n", typeName)
	} else {
		b.WriteString("        Map<String, Object> m = Json.asMap(o);\n")
		fmt.Fprintf(&b, "        return new %s(\n", typeName)
		for i, f := range fields {
			expr := fmt.Sprintf("m.get(%q)", f.Name)
			comma := ","
			if i == len(fields)-1 {
				comma = ""
			}
			fmt.Fprintf(&b, "            %s%s\n", javaDecode(doc, f.Schema, expr, 0), comma)
		}
		b.WriteString("        );\n")
	}
	b.WriteString("    }\n\n")

	// toJson: rebuild the wire Map, restoring original key names and encoding
	// nested records/lists back to plain Map/List trees.
	b.WriteString("    public Object toJson() {\n")
	b.WriteString("        Map<String, Object> m = new LinkedHashMap<>();\n")
	for _, f := range fields {
		acc := javaFieldName(f.Name) + "()"
		fmt.Fprintf(&b, "        m.put(%q, %s);\n", f.Name, javaEncode(doc, f.Schema, acc, 0))
	}
	b.WriteString("        return m;\n")
	b.WriteString("    }\n")

	b.WriteString("}\n")
	return b.String()
}

// javaClient renders the Client: constructors, a single request helper on
// java.net.http, and one typed method per operation.
func javaClient(doc *core.Document, pkg string, opts Options) string {
	var b strings.Builder
	fmt.Fprintf(&b, "package %s;\n\n", pkg)
	b.WriteString("import java.net.URI;\n")
	b.WriteString("import java.net.URLEncoder;\n")
	b.WriteString("import java.net.http.HttpClient;\n")
	b.WriteString("import java.net.http.HttpRequest;\n")
	b.WriteString("import java.net.http.HttpResponse;\n")
	b.WriteString("import java.nio.charset.StandardCharsets;\n")
	b.WriteString("import java.util.*;\n\n")
	b.WriteString("// Code generated by specter. Edit freely — it is yours now.\n")

	b.WriteString("public final class Client {\n")
	fmt.Fprintf(&b, "    public static final String DEFAULT_BASE_URL = %s;\n\n", javaString(opts.BaseURL))
	b.WriteString("    private final String baseUrl;\n")
	b.WriteString("    private final String token;\n")
	b.WriteString("    private final HttpClient http = HttpClient.newHttpClient();\n\n")

	b.WriteString("    public Client() { this(DEFAULT_BASE_URL, null); }\n")
	b.WriteString("    public Client(String baseUrl) { this(baseUrl, null); }\n")
	b.WriteString("    public Client(String baseUrl, String token) {\n")
	b.WriteString("        this.baseUrl = baseUrl.replaceAll(\"/$\", \"\");\n")
	b.WriteString("        this.token = token;\n")
	b.WriteString("    }\n\n")

	// The one request helper every operation funnels through.
	b.WriteString(`    private Object request(String method, String path, Map<String, Object> query, Object body) {
        try {
            StringBuilder url = new StringBuilder(baseUrl + path);
            if (query != null) {
                boolean first = true;
                for (Map.Entry<String, Object> e : query.entrySet()) {
                    if (e.getValue() == null) continue;
                    url.append(first ? "?" : "&");
                    first = false;
                    url.append(URLEncoder.encode(e.getKey(), StandardCharsets.UTF_8));
                    url.append("=");
                    url.append(URLEncoder.encode(String.valueOf(e.getValue()), StandardCharsets.UTF_8));
                }
            }
            HttpRequest.Builder rb = HttpRequest.newBuilder(URI.create(url.toString()));
            if (token != null) rb.header("Authorization", "Bearer " + token);
            if (body != null) {
                rb.header("Content-Type", "application/json");
                rb.method(method, HttpRequest.BodyPublishers.ofString(Json.write(body)));
            } else {
                rb.method(method, HttpRequest.BodyPublishers.noBody());
            }
            HttpResponse<String> res = http.send(rb.build(), HttpResponse.BodyHandlers.ofString());
            String text = res.body();
            Object data = (text == null || text.isEmpty()) ? null : Json.parse(text);
            if (res.statusCode() < 200 || res.statusCode() > 299) {
                throw new ApiException(res.statusCode(), data);
            }
            return data;
        } catch (java.io.IOException | InterruptedException e) {
            throw new RuntimeException(e);
        }
    }
`)

	for _, op := range flatten(doc) {
		writeJavaMethod(&b, doc, op)
	}

	b.WriteString("}\n")
	return b.String()
}

func writeJavaMethod(b *strings.Builder, doc *core.Document, op operation) {
	var params []string
	for _, p := range op.PathParams {
		params = append(params, "String "+javaParamName(p))
	}
	if op.Body != nil {
		params = append(params, javaType(doc, op.Body)+" body")
	}
	if len(op.Query) > 0 {
		params = append(params, "Map<String, Object> query")
	}

	result := "void"
	if op.Result != nil {
		result = javaType(doc, op.Result)
	}

	b.WriteString("\n")
	if op.Summary != "" {
		fmt.Fprintf(b, "    /** %s */\n", op.Summary)
	}
	if op.Deprecated {
		b.WriteString("    @Deprecated\n")
	}
	fmt.Fprintf(b, "    public %s %s(%s) {\n", result, javaMethodName(op.Name), strings.Join(params, ", "))

	fmt.Fprintf(b, "        String path = %s;\n", javaString(op.Path))
	for _, p := range op.PathParams {
		fmt.Fprintf(b, "        path = path.replace(%q, String.valueOf(%s));\n", "{"+p+"}", javaParamName(p))
	}

	query := "null"
	if len(op.Query) > 0 {
		query = "query"
	}
	body := "null"
	if op.Body != nil {
		body = javaEncode(doc, op.Body, "body", 0)
	}

	if result == "void" {
		fmt.Fprintf(b, "        request(%q, path, %s, %s);\n", op.Method, query, body)
	} else {
		fmt.Fprintf(b, "        Object data = request(%q, path, %s, %s);\n", op.Method, query, body)
		fmt.Fprintf(b, "        return %s;\n", javaDecode(doc, op.Result, "data", 0))
	}
	b.WriteString("    }\n")
}

// javaType maps a schema to a Java type. Refs resolve through aliases and
// non-object schemas to a concrete type; structs become their record name.
func javaType(doc *core.Document, s *core.Schema) string {
	if s == nil {
		return "Object"
	}
	if s.Ref != "" {
		target := doc.Components.Schemas[refName(s.Ref)]
		if target == nil {
			return "Object"
		}
		if isStruct(target) && aliasTarget(target) == nil {
			return pascalCase(refName(s.Ref))
		}
		if a := aliasTarget(target); a != nil {
			return javaType(doc, a)
		}
		return javaType(doc, target)
	}
	switch s.Type {
	case "string":
		return "String"
	case "integer":
		return "long"
	case "number":
		return "double"
	case "boolean":
		return "boolean"
	case "array":
		return "List<" + javaBox(javaType(doc, s.Items)) + ">"
	case "object":
		return "Map<String, Object>"
	}
	return "Object"
}

// javaBox turns a primitive type name into its wrapper for use in generics.
func javaBox(t string) string {
	switch t {
	case "long":
		return "Long"
	case "double":
		return "Double"
	case "boolean":
		return "Boolean"
	}
	return t
}

// javaDecode builds the expression turning a wire value (expr) into the typed
// field: a referenced record via fromJson, an array element-wise, a primitive
// through a Json coercion helper. depth keeps nested-lambda parameters unique.
func javaDecode(doc *core.Document, s *core.Schema, expr string, depth int) string {
	if s == nil {
		return expr
	}
	if s.Ref != "" {
		target := doc.Components.Schemas[refName(s.Ref)]
		if target != nil && isStruct(target) && aliasTarget(target) == nil {
			return fmt.Sprintf("%s.fromJson(%s)", pascalCase(refName(s.Ref)), expr)
		}
		if target != nil {
			if a := aliasTarget(target); a != nil {
				return javaDecode(doc, a, expr, depth)
			}
			return javaDecode(doc, target, expr, depth)
		}
		return expr
	}
	switch s.Type {
	case "string":
		return fmt.Sprintf("Json.asString(%s)", expr)
	case "integer":
		return fmt.Sprintf("Json.asLong(%s)", expr)
	case "number":
		return fmt.Sprintf("Json.asDouble(%s)", expr)
	case "boolean":
		return fmt.Sprintf("Json.asBool(%s)", expr)
	case "array":
		v := fmt.Sprintf("x%d", depth)
		inner := javaDecode(doc, s.Items, v, depth+1)
		return fmt.Sprintf("Json.mapList(Json.asList(%s), %s -> %s)", expr, v, inner)
	case "object":
		return fmt.Sprintf("Json.asMap(%s)", expr)
	}
	return expr
}

// javaEncode builds the expression turning a typed value (expr) back into a
// plain Map/List/primitive tree for the wire: records via toJson, arrays
// element-wise, primitives unchanged.
func javaEncode(doc *core.Document, s *core.Schema, expr string, depth int) string {
	if s == nil {
		return expr
	}
	if s.Ref != "" {
		target := doc.Components.Schemas[refName(s.Ref)]
		if target != nil && isStruct(target) && aliasTarget(target) == nil {
			return fmt.Sprintf("(%s == null ? null : %s.toJson())", expr, expr)
		}
		if target != nil {
			if a := aliasTarget(target); a != nil {
				return javaEncode(doc, a, expr, depth)
			}
			return javaEncode(doc, target, expr, depth)
		}
		return expr
	}
	if s.Type == "array" && s.Items != nil {
		v := fmt.Sprintf("x%d", depth)
		inner := javaEncode(doc, s.Items, v, depth+1)
		if inner == v {
			return expr // primitive elements are already wire-ready
		}
		return fmt.Sprintf("Json.mapList(%s, %s -> %s)", expr, v, inner)
	}
	return expr
}

// javaString renders a Go string as a Java double-quoted literal.
func javaString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString("\\\"")
		case '\\':
			b.WriteString("\\\\")
		case '\n':
			b.WriteString("\\n")
		case '\r':
			b.WriteString("\\r")
		case '\t':
			b.WriteString("\\t")
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func javaFieldName(name string) string  { return javaIdent(camelCase(name)) }
func javaMethodName(name string) string { return javaIdent(camelCase(name)) }

func javaParamName(name string) string {
	n := javaIdent(camelCase(name))
	switch n {
	case "query", "body", "path", "data", "url", "method":
		return n + "Param"
	}
	return n
}

func javaIdent(n string) string {
	if n == "" {
		return "field_"
	}
	if javaReserved[n] {
		return n + "_"
	}
	if n[0] >= '0' && n[0] <= '9' {
		return "f_" + n
	}
	return n
}

